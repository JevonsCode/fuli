class StoredFieldError(ValueError):
    """A map write that does not match the persisted-field contract."""


def stored_fields(owner: str, values: dict) -> dict:
    """A map a write stores on a record of this label or relationship type:
    every key declared, every value of its declared type, null only where the
    property may be missing. A relationship type the contract does not list
    stores no properties. Returns the map unchanged."""
    fields = NODE_FIELDS.get(owner) or RELATIONSHIP_FIELDS.get(owner, {})
    unknown = sorted(set(values) - set(fields))
    if unknown:
        raise StoredFieldError(f'{owner} write has undeclared properties {", ".join(unknown)}: '
                               'declare them in graph_field_contract.py with the next graph version')
    for name, value in values.items():
        declared = fields[name]
        if value is None:
            if not declared.endswith('?'):
                raise StoredFieldError(f'{owner}.{name} may not be null')
        elif not any(_matches(kind, value) for kind in declared.rstrip('?').split('|')):
            raise StoredFieldError(f'{owner}.{name} must be {declared.rstrip("?")}, not {value!r:.80}')
    return values


def carried_fields(owner: str, carried: dict, overrides: dict) -> tuple[dict, list[str]]:
    """A record copied forward from a stored one (a new version, a copied
    relationship): the overrides the code sets are checked like stored_fields;
    the carried properties pass through verbatim, so a property an older FULI
    stored and this contract does not declare survives the copy instead of
    refusing it. Returns the record and the carried undeclared keys, which the
    caller records so the next graph version can declare them."""
    stored_fields(owner, overrides)
    fields = NODE_FIELDS.get(owner) or RELATIONSHIP_FIELDS.get(owner, {})
    legacy = sorted(set(carried) - set(fields) - set(overrides))
    return {**carried, **overrides}, legacy


def _matches(kind: str, value) -> bool:
    if kind.endswith('[]'):
        return isinstance(value, (list, tuple)) and all(_matches(kind[:-2], item) for item in value)
    if kind in ENUMS:
        return value in ENUMS[kind]
    return _SCALARS[kind](value)


_SCALARS = {
    'string': lambda value: isinstance(value, str),
    'integer': lambda value: isinstance(value, int) and not isinstance(value, bool),
    'float': lambda value: isinstance(value, (int, float)) and not isinstance(value, bool),
    'boolean': lambda value: isinstance(value, bool),
    'datetime': lambda value: isinstance(value, (datetime, Neo4jDateTime)),
    'date': lambda value: isinstance(value, (date, Neo4jDate)) and not isinstance(value, datetime),
}
