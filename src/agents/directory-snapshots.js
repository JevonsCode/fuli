import { createHash } from 'node:crypto';
import {
  closeSync,
  lstatSync,
  mkdirSync,
  openSync,
  readFileSync,
  unlinkSync
} from 'node:fs';
import { join } from 'node:path';

import { detectSensitiveContent } from '../security/sensitive-content.js';
import { writeTextFileAtomic } from '../storage/json-file.js';

// Generated Markdown views of a durable Agent. The database owns identity and
// memory; these files are a projection for viewing and handoff and are never
// read back as memory. Only files named here are written; others are kept.
const MANIFEST = '.fuli-snapshot.json';
const LOCK = '.fuli-snapshot.lock';
// A lock older than this was left by a writer that exited mid-write.
const LOCK_STALE_MS = 30_000;
const FILE_KEY = /^(?:AGENTS\.md|MEMORY\.md|projects\/[0-9a-f]{32}\/MEMORY\.md)$/;
const HASH = /^[0-9a-f]{64}$/;
const NOTICE = 'Generated by FULI from its database for viewing and handoff. '
  + 'This file is not the authority: edits are not imported and may be replaced. '
  + 'Change this Agent or its memory through FULI.';

class UnsafePath extends Error {}
class Busy extends Error {}

/**
 * One directory per durable Agent: <root>/<provider>/<space>/<agent>, each
 * component a hash of its stable ID so display names and unsafe IDs never
 * shape a path. Every call is synchronous inside a short, non-blocking lock
 * and never throws; it returns a small status with relative paths only.
 */
export function createAgentDirectorySnapshots({ root, providerIdentity, now = () => new Date() }) {
  // The same Provider with or without a trailing slash shares one namespace.
  const providerKey = key(String(providerIdentity).replace(/\/+$/, ''));

  function withAgentDirectory(personalSpaceId, agentId, update) {
    const parts = [providerKey, key(personalSpaceId), key(agentId)];
    const path = ['agents', ...parts].join('/');
    try {
      const directory = parts.reduce((parent, part) => ensureDirectory(join(parent, part)), ensureDirectory(root));
      const release = acquire(join(directory, LOCK));
      try {
        const manifest = readManifest(join(directory, MANIFEST));
        const files = update(directory, manifest);
        if (manifest.dirty) writeTextFileAtomic(join(directory, MANIFEST), `${JSON.stringify({ version: 1, files: manifest.files }, null, 2)}\n`);
        return { status: overall(files), path, files };
      } finally { release(); }
    } catch (error) {
      return { status: error instanceof UnsafePath ? 'unsafe_path' : error instanceof Busy ? 'busy' : 'unavailable', path };
    }
  }

  // Project the identity and the memory layers this caller already read and
  // was authorized for. Nothing else is fetched; a layer absent here is kept.
  function materialize({ personalSpaceId, agent, layers = [] }) {
    if (!agent?.agentId || agent.memoryScope !== 'reviewed_agent') return null;
    let artifacts;
    try {
      artifacts = [identityArtifact(agent), ...layers.map(layerArtifact)];
    } catch {
      return { status: 'unavailable', path: null };
    }
    const generatedAt = now().toISOString();
    return withAgentDirectory(personalSpaceId, agent.agentId,
      (directory, manifest) => artifacts.map(artifact => project(directory, manifest, artifact, generatedAt)));
  }

  // A committed write whose content is not available here: record the newer
  // revision so the files report "stale" until the next authorized read.
  function markStale({ personalSpaceId, agentId, personalProjectId = null, revision }) {
    if (!agentId || !Number.isSafeInteger(revision)) return null;
    const file = layerFile(personalProjectId);
    return withAgentDirectory(personalSpaceId, agentId, (_directory, manifest) => {
      const entry = manifest.files[file];
      if (entry && entry.order >= revision) {
        // A delayed older mark never hides a newer revision that is still pending.
        return entry.pending !== undefined && entry.pending > entry.order
          ? [fileStatus({ file, revision: entry.pending }, 'stale')]
          : [fileStatus({ file, revision: entry.order }, 'unchanged')];
      }
      manifest.files[file] = { order: entry?.order ?? -1, bodyHash: entry?.bodyHash ?? null,
        fileHash: entry?.fileHash ?? null, pending: Math.max(revision, entry?.pending ?? -1) };
      manifest.dirty = true;
      return [fileStatus({ file, revision }, 'stale')];
    });
  }

  return { materialize, markStale };
}

function project(directory, manifest, artifact, generatedAt) {
  const entry = manifest.files[artifact.file];
  // An older revision never replaces a newer one, even if its file was removed.
  if (entry && entry.order > artifact.order) return fileStatus(artifact, 'newer_present');
  const segments = artifact.file.split('/');
  const parent = segments.slice(0, -1).reduce((path, part) => ensureDirectory(join(path, part)), directory);
  const target = join(parent, segments.at(-1));
  // Rejects a symlink or non-file in the managed name before anything else.
  const existing = fileHash(target);
  const bodyHash = sha(artifact.render(null));
  const pending = entry?.pending !== undefined && entry.pending > artifact.order ? entry.pending : undefined;
  const intact = entry && existing === entry.fileHash;
  if (intact && entry.order === artifact.order && entry.bodyHash === bodyHash) {
    if (entry.pending !== undefined && pending === undefined) {
      delete entry.pending;
      manifest.dirty = true;
    }
    return fileStatus(artifact, pending === undefined ? 'unchanged' : 'stale');
  }
  const content = artifact.render(generatedAt);
  writeTextFileAtomic(target, content);
  manifest.files[artifact.file] = { order: artifact.order, bodyHash, fileHash: sha(content),
    ...(pending === undefined ? {} : { pending }) };
  manifest.dirty = true;
  return fileStatus(artifact, pending === undefined ? 'written' : 'stale');
}

function fileStatus(artifact, state) {
  return { file: artifact.file, scope: artifact.file === 'AGENTS.md' ? 'identity'
    : artifact.file === 'MEMORY.md' ? 'global' : 'project',
  ...(artifact.file === 'AGENTS.md' ? {} : { revision: artifact.revision }), state };
}

function overall(files) {
  if (files.some(file => file.state === 'stale')) return 'stale';
  if (files.some(file => file.state === 'newer_present')) return 'newer_present';
  return 'current';
}

function identityArtifact(agent) {
  const profile = agent.profile ?? {};
  const updated = Date.parse(agent.updatedAt);
  const title = line(profile.displayName || profile.name) || agent.agentId;
  const facts = [
    ['Agent ID', `\`${line(agent.agentId)}\``],
    ['Role', profile.displayName && profile.name ? line(profile.name) : null],
    ['Employee number', agent.employeeNumber ?? null],
    ['Type', line(profile.agentType)],
    ['Status', line(profile.status)],
    ['Memory', 'durable: one global layer plus one layer per assigned project']
  ].filter(([, value]) => value !== null && value !== undefined && value !== '');
  const sections = [
    ['Responsibility', text(profile.responsibility)],
    ['Capabilities', list(profile.capabilities)],
    ['Work kinds', list(profile.workKinds)],
    ['Initial preferences', list(profile.initialPreferences)],
    ['Judgment', text(profile.character?.judgment)],
    ['Taste', text(profile.character?.taste)],
    ['Personality', text(profile.character?.personality)],
    ['Expectations', text(profile.expectations)]
  ];
  return { file: 'AGENTS.md', order: Number.isSafeInteger(updated) ? updated : 0,
    render: generatedAt => document(`# ${title}`, [
      ...facts.map(([label, value]) => `- ${label}: ${value}`),
      ...(generatedAt ? [`- Generated: ${generatedAt}`] : [])
    ], sections) };
}

function layerArtifact({ personalProjectId = null, revision, current }) {
  const memory = current?.memory ?? null;
  const global = personalProjectId === null;
  return { file: layerFile(personalProjectId), revision, order: revision,
    render: generatedAt => document(global ? '# Working memory: global' : '# Working memory: project', [
      ...(global ? [] : [`- Project ID: \`${line(personalProjectId)}\``]),
      `- Scope: ${global ? 'private_agent_global' : 'private_agent_project'}`,
      `- Database revision: ${revision}`,
      ...(current?.createdAt ? [`- Recorded: ${line(current.createdAt)}`] : []),
      ...(generatedAt ? [`- Generated: ${generatedAt}`] : [])
    ], memory ? [
      ['Summary', text(memory.summary)],
      ['Decisions', list(memory.decisions)],
      ['Open threads', list(memory.openThreads)],
      ['Next actions', list(memory.nextActions)]
    ] : [['Summary', 'No working memory has been recorded in this scope yet.']]) };
}

/**
 * One Markdown handoff file for an Agent and exactly one memory scope, from a
 * view the caller already read from the database and scope-checked. It carries
 * the same allow-listed identity and memory fields as the directory files.
 */
export function renderAgentMemoryExport({ agent, personalProjectId = null, revision, current, generatedAt }) {
  const identity = identityArtifact(agent).render(null);
  const layer = layerArtifact({ personalProjectId, revision, current }).render(generatedAt);
  const scope = personalProjectId === null ? 'global' : `project-${fileLabel(personalProjectId)}`;
  return {
    filename: `fuli-${fileLabel(agent.agentId)}-${scope}-memory-r${revision}.md`,
    // Each part keeps its own notice so either can be read on its own.
    markdown: `${identity}\n${layer}`
  };
}

/**
 * The handoff an Agent leaves when it is dismissed: identity, why it left, the
 * lessons kept, and every memory layer the caller read and scope-checked.
 */
export function renderAgentHandoff({ agent, reason, lessons, layers, generatedAt }) {
  const identity = identityArtifact(agent).render(null);
  const projects = (agent.assignments ?? []).filter(item => item.status === 'active')
    .map(item => `\`${line(item.personalProjectId)}\``);
  const departure = document('# Handoff: dismissal', [
    `- Prepared: ${generatedAt}`,
    ...(projects.length ? [`- Assignments ended: ${projects.join(', ')}`] : [])
  ], [['Reason', text(reason)], ['Lessons', list(lessons)]]);
  const memory = layers.length
    ? layers.map(layer => layerArtifact(layer).render(generatedAt))
    : [document('# Working memory', ['- Scope: none'], [['Summary', 'This Agent keeps no reviewed working memory.']])];
  return { filename: `fuli-${fileLabel(agent.agentId)}-handoff.md`, markdown: [identity, departure, ...memory].join('\n') };
}

// A safe ID is used as is; anything else becomes a short stable hash.
function fileLabel(value) {
  return /^[a-z0-9][a-z0-9._-]{0,63}$/i.test(value) ? value : key(value).slice(0, 12);
}

function layerFile(personalProjectId) {
  return personalProjectId === null ? 'MEMORY.md' : `projects/${key(personalProjectId)}/MEMORY.md`;
}

function document(title, facts, sections) {
  const body = sections.filter(([, value]) => value).map(([heading, value]) => `## ${heading}\n\n${value}`);
  // Credentials are rejected on write; anything older that looks like one stays in FULI.
  const withheld = detectSensitiveContent(body.join('\n')).restricted
    ? ['## Content withheld\n\nThis content looks like it contains credentials. View it in FULI.'] : body;
  return `${[title, `> ${NOTICE}`, facts.join('\n'), ...withheld].join('\n\n')}\n`;
}

function line(value) {
  return typeof value === 'string' ? value.replace(/\s+/g, ' ').trim() : value;
}

function text(value) {
  return typeof value === 'string' && value.trim() ? value.trim() : null;
}

function list(values) {
  const items = Array.isArray(values) ? values.filter(value => typeof value === 'string' && value.trim()) : [];
  return items.length ? items.map(value => `- ${line(value)}`).join('\n') : null;
}

function key(value) {
  return createHash('sha256').update(String(value)).digest('hex').slice(0, 32);
}

function sha(value) {
  return createHash('sha256').update(value).digest('hex');
}

function ensureDirectory(path) {
  let stat;
  try { stat = lstatSync(path); } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
    mkdirSync(path, { mode: 0o700 });
    stat = lstatSync(path);
  }
  if (stat.isSymbolicLink() || !stat.isDirectory()) throw new UnsafePath();
  return path;
}

function fileHash(path) {
  let stat;
  try { stat = lstatSync(path); } catch (error) {
    if (error?.code === 'ENOENT') return null;
    throw error;
  }
  if (stat.isSymbolicLink() || !stat.isFile()) throw new UnsafePath();
  return sha(readFileSync(path));
}

// Non-blocking: a concurrent writer means "busy", never a wait.
function acquire(path) {
  const take = () => closeSync(openSync(path, 'wx', 0o600));
  try { take(); } catch (error) {
    if (error?.code !== 'EEXIST') throw error;
    const stat = lstatSync(path);
    if (stat.isSymbolicLink() || !stat.isFile()) throw new UnsafePath();
    if (Date.now() - stat.mtimeMs < LOCK_STALE_MS) throw new Busy();
    unlinkSync(path);
    try { take(); } catch (retry) { throw retry?.code === 'EEXIST' ? new Busy() : retry; }
  }
  return () => { try { unlinkSync(path); } catch { /* already released */ } };
}

// An unreadable, edited or unknown manifest only costs a regeneration.
function readManifest(path) {
  const files = {};
  const text = fileHash(path) === null ? null : readFileSync(path, 'utf8');
  try {
    const value = text === null ? null : JSON.parse(text);
    if (value?.version === 1 && value.files && typeof value.files === 'object' && !Array.isArray(value.files)) {
      for (const [file, entry] of Object.entries(value.files)) {
        if (FILE_KEY.test(file) && validEntry(entry)) {
          files[file] = { order: entry.order, bodyHash: entry.bodyHash, fileHash: entry.fileHash,
            ...(entry.pending === undefined ? {} : { pending: entry.pending }) };
        }
      }
    }
  } catch { /* regenerate from the database */ }
  return { files, dirty: false };
}

function validEntry(entry) {
  return Boolean(entry) && typeof entry === 'object'
    && Number.isSafeInteger(entry.order) && entry.order >= -1
    && (entry.bodyHash === null || HASH.test(entry.bodyHash))
    && (entry.fileHash === null || HASH.test(entry.fileHash))
    && (entry.pending === undefined || (Number.isSafeInteger(entry.pending) && entry.pending >= 0));
}
