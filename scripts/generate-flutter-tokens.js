#!/usr/bin/env node
// Generates the desktop client's design tokens from the console's theme, so the
// Flutter window and the web console share one source of truth:
// web/src/styles/theme/base.css (scales) and semantic.css (the default skin,
// light mode). Run `node scripts/generate-flutter-tokens.js` after changing
// either file; test/flutter-tokens.test.js fails while the output is stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const BASE_CSS = join(root, 'web/src/styles/theme/base.css')
const SEMANTIC_CSS = join(root, 'web/src/styles/theme/semantic.css')
export const OUTPUT = join(root, 'desktop/flutter/lib/src/ui/fuli_tokens.g.dart')

// The declarations of the first `:root { … }` block, comments removed.
function declarations(css) {
  const start = css.indexOf(':root {')
  const body = css.slice(start, css.indexOf('}', start)).replace(/\/\*[\s\S]*?\*\//g, '')
  return [...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => ({ name, value: value.trim() }))
}

const camel = (name) => name.replace(/^--/, '').replace(/-(\w)/g, (_, letter) => letter.toUpperCase())
const dartNumber = (value) => (Number.isInteger(value) ? `${value}.0` : String(value))
const hex2 = (part) => part.toString(16).padStart(2, '0').toUpperCase()
const argb = (alpha, [r, g, b]) => `Color(0x${[alpha, r, g, b].map(hex2).join('')})`
const alphaOf = (percent) => Math.round((percent / 100) * 255)

function px(value) {
  const match = /^(-?[\d.]+)px$/.exec(value)
  if (!match) throw new Error(`expected a px value, got ${value}`)
  return Number(match[1])
}

// A hex or `rgb(r g b / a%)` colour; anything else (var(), …) is not a literal.
function colourLiteral(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value)?.[1]
  if (hex) return argb(255, [0, 2, 4].map((at) => Number.parseInt(hex.slice(at, at + 2), 16)))
  const rgb = /^rgb\((\d+) (\d+) (\d+) \/ (\d+)%\)$/.exec(value)
  return rgb ? argb(alphaOf(Number(rgb[4])), rgb.slice(1, 4).map(Number)) : null
}

// "rgb(var(--shadow-rgb) / 8%)" → the shadow ink at that alpha.
function inkColour(value, ink) {
  const match = /^rgb\(var\(--shadow-rgb\) \/ (\d+)%\)$/.exec(value)
  if (!match) throw new Error(`expected rgb(var(--shadow-rgb) / n%), got ${value}`)
  return argb(alphaOf(Number(match[1])), ink)
}

// "0 6px 20px rgb(var(--shadow-rgb) / 7%), …" → BoxShadows on the shadow ink.
function shadowLayers(value, ink) {
  return value.split(/,(?![^(]*\))/).map((layer) => {
    const match = /^\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)px\s+rgb\(var\(--shadow-rgb\) \/ (\d+)%\)\s*$/.exec(layer)
    if (!match) throw new Error(`unsupported shadow layer: ${layer}`)
    const [x, y, blur, percent] = match.slice(1).map(Number)
    return `BoxShadow(color: ${argb(alphaOf(percent), ink)}, offset: Offset(${dartNumber(x)}, ${dartNumber(y)}), blurRadius: ${dartNumber(blur)})`
  })
}

export function generate({ base = readFileSync(BASE_CSS, 'utf8'), semantic = readFileSync(SEMANTIC_CSS, 'utf8') } = {}) {
  const scale = declarations(base)
  // The light default skin only: the reserved dark block sits after @media.
  const meaning = declarations(semantic.slice(0, semantic.indexOf('@media')))
  const ink = meaning.find(({ name }) => name === '--shadow-rgb').value.split(/\s+/).map(Number)
  const pick = (list, prefix) => list.filter(({ name }) => name.startsWith(prefix))
  // `strip` drops the prefix (--text-body → body); otherwise the full name stays (--radius-card → radiusCard).
  const constants = (prefix, render, strip = false) => pick(scale, prefix)
    .map(({ name, value }) => `  static const ${camel(strip ? name.replace(prefix, '--') : name)} = ${render(value)};`)
  const colours = pick(meaning, '--color-')
    .map(({ name, value }) => [camel(name.replace('--color-', '--')), colourLiteral(value)])
    .filter(([, colour]) => colour)
  const meant = (name) => meaning.find((entry) => entry.name === name).value
  const dockBlur = /blur\(([^)]+)\)/.exec(meant('--filter-dock'))[1]
  const ease = /cubic-bezier\(([^)]+)\)/.exec(scale.find(({ name }) => name === '--motion-ease').value)[1]
    .split(',').map((part) => dartNumber(Number(part)))

  return `// GENERATED by scripts/generate-flutter-tokens.js from web/src/styles/theme/
// base.css and semantic.css (default skin, light mode). Do not edit by hand:
// change the console's theme and run \`node scripts/generate-flutter-tokens.js\`.

import 'package:flutter/animation.dart';
import 'package:flutter/painting.dart';

abstract final class FuliColors {
${colours.map(([name, colour]) => `  static const ${name} = ${colour};`).join('\n')}
}

abstract final class FuliText {
${constants('--text-', (value) => dartNumber(px(value)), true).join('\n')}
${constants('--weight-', (value) => `FontWeight.w${value}`).join('\n')}
${constants('--leading-', (value) => dartNumber(Number(value))).join('\n')}
}

abstract final class FuliSpace {
${constants('--space-', (value) => dartNumber(px(value))).join('\n')}
}

abstract final class FuliSize {
${constants('--control-', (value) => dartNumber(px(value))).join('\n')}
${constants('--radius-', (value) => dartNumber(px(value))).join('\n')}
}

abstract final class FuliShadow {
${pick(scale, '--shadow-').map(({ name, value }) =>
    `  static const ${camel(name.replace('--shadow-', '--'))} = [\n    ${shadowLayers(value, ink).join(',\n    ')},\n  ];`).join('\n')}
}

// The dock's frosted glass: every floating or pinned bar takes it.
abstract final class FuliGlass {
  static const surface = ${colourLiteral(meant('--surface-dock'))};
  static const edge = ${inkColour(meant('--edge-dock'), ink)};
  static const blur = ${dartNumber(px(dockBlur))};
}

abstract final class FuliMotion {
${pick(scale, '--motion-').filter(({ name }) => /^--motion-(fast|medium)$/.test(name))
    .map(({ name, value }) => `  static const ${camel(name.replace('--motion-', '--'))} = Duration(milliseconds: ${Number.parseInt(value, 10)});`).join('\n')}
  static const ease = Cubic(${ease.join(', ')});
}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, generate())
  console.log(`wrote ${OUTPUT}`)
}
